export type Strings = typeof zhCN

/** Resolve a BCP-47-ish tag into a supported locale, falling back to zh-CN. */
export function resolveLocale(setting: 'auto' | string, systemTag: string): Locale {
  if (setting === 'zh-CN' || setting === 'en') return setting
  const tag = (systemTag || '').toLowerCase()
  if (tag.startsWith('en')) return 'en'
  if (tag.startsWith('zh')) return 'zh-CN'
  return 'zh-CN'
}

/** Simple `{placeholder}` formatter. */
export function fmt(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    key in params ? String(params[key]) : `{${key}}`
  )
}
